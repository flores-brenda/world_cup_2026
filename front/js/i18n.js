let currentLang = localStorage.getItem('appLang') || 'fr';

// Helper: get translation for current language
function t(key) {
  const lang = translations[currentLang] || translations['fr'];
  if (lang && lang[key] !== undefined) return lang[key];
  if (translations['fr'] && translations['fr'][key] !== undefined) return translations['fr'][key];
  return key;
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('appLang', lang);

  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Update specific elements without data attribute (or with HTML inside)
  document.title = translations[lang].title;

  // Highlight active lang button
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });
}

function initI18n() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      setLanguage(e.target.getAttribute('data-lang'));
    });
  });
  // Initial call
  setLanguage(currentLang);
}
